#!/usr/bin/env node
/**
 * Generate the update-signing keypair.
 *
 * Apple code signing cannot protect this update channel: a delta update rewrites
 * the app bundle and re-signs it ad-hoc on the user's own machine, so the
 * signature proves nothing about where the payload came from. The manifest
 * therefore carries its own Ed25519 signature, checked against a public key
 * compiled into the app — the same approach Sparkle takes, and for the same
 * reason. Without it an update would be trusted purely because TLS said so.
 *
 * The private key never enters the repository. It is written outside it, and
 * `make-update.mjs` reads it from there or from FR_UPDATE_KEY.
 *
 *   node scripts/make-update-key.mjs
 *
 * Run once. Re-running mints a new identity that existing installs will reject,
 * which is a deliberate speed bump: losing this key means losing the ability to
 * ship updates to anyone who already has the app.
 */
import { generateKeyPairSync } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const KEY_DIR = path.join(os.homedir(), '.config', 'focus-reader');
const KEY_PATH = path.join(KEY_DIR, 'update-signing-key.pem');
const PUB_PATH = path.join(ROOT, 'src', 'shared', 'update', 'public-key.ts');

if (fs.existsSync(KEY_PATH) && !process.argv.includes('--force')) {
  console.error(
    `A signing key already exists at ${KEY_PATH}.\n` +
      'Replacing it will orphan every install that trusts the current public key.\n' +
      'Pass --force if that is genuinely what you want.',
  );
  process.exit(1);
}

const { publicKey, privateKey } = generateKeyPairSync('ed25519');

fs.mkdirSync(KEY_DIR, { recursive: true });
fs.writeFileSync(KEY_PATH, privateKey.export({ type: 'pkcs8', format: 'pem' }), { mode: 0o600 });

const spki = publicKey.export({ type: 'spki', format: 'der' }).toString('base64');

fs.mkdirSync(path.dirname(PUB_PATH), { recursive: true });
fs.writeFileSync(
  PUB_PATH,
  `/**
 * Public half of the update-signing keypair, generated by
 * scripts/make-update-key.mjs. Safe to publish — it can only verify.
 *
 * An update manifest that does not carry a valid signature under this key is
 * discarded before its contents are read, so a compromised release host cannot
 * push code to anyone.
 */
export const UPDATE_PUBLIC_KEY_SPKI_BASE64 =
  '${spki}';
`,
);

console.log(`private key -> ${KEY_PATH} (mode 600, outside the repo)`);
console.log(`public key  -> ${path.relative(ROOT, PUB_PATH)}`);
